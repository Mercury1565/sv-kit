"""OpenSTA static timing adapter (open-source flow).

`run()` writes a TCL script into the work dir (read_liberty, read_verilog, link_design, an SDC —
the user's `flow.sdc` or a generated clock-only one — then report_checks / report_worst_slack /
report_tns / report_power), runs `sta`, and parses the combined output.

Everything is normalised to svkit units: the library time unit is read from `report_units`
and converted to ps; report_power's Watts are converted to mW. The parsers are pure functions
(`parse_report`, `parse_timing`) so they are golden-testable offline.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Optional

from svkit.adapters.base import RunContext, StaAdapter
from svkit.config import StaFlow
from svkit.core import project as P
from svkit.schemas import Msg, Power, Severity, SynthResult, TimingPath, TimingPoint

MARK = "@@svkit"
_TIME_UNITS = {"fs": 1e-3, "ps": 1.0, "ns": 1e3, "us": 1e6, "ms": 1e9, "s": 1e12}
_POWER_UNITS = {"W": 1e3, "mW": 1.0, "uW": 1e-3, "nW": 1e-6, "pW": 1e-9}
DEFAULT_PERIOD_PS = 10000.0


# ---------------------------------------------------------------------------- TCL generation
def _tcl_list(items) -> str:
    return " ".join("{" + str(i) + "}" for i in items)


_SIGNED_DECL = re.compile(r"^(\s*(?:input|output|inout|wire|reg)\s+)signed\s+", re.M)


def sta_netlist(netlist: Path, workdir: Path) -> Path:
    """OpenSTA's Verilog reader rejects `signed` in declarations, which yosys writes for signed
    ports. Signedness has no meaning in a gate netlist, so STA reads a copy without it."""
    text = netlist.read_text(errors="replace")
    clean = _SIGNED_DECL.sub(r"\1", text)
    if clean == text:
        return netlist
    out = workdir / f"{netlist.stem}.sta.v"
    out.write_text(clean)
    return out


def build_tcl(*, liberty: list[Path], netlist: Path, top: str, clock: str, period_lib: Optional[float],
              sdc: Optional[Path], max_paths: int) -> str:
    """The STA script. `period_lib` is in the LIBRARY time unit (None = keep the SDC's clock)."""
    lines = ["# generated by svkit (OpenStaAdapter) -- safe to delete", "set svkit_ok 1"]
    for lib in liberty:
        lines.append(f"read_liberty {{{lib}}}")
    lines += [f"read_verilog {{{netlist}}}", f"link_design {{{top}}}"]
    if sdc is not None:
        lines.append(f"read_sdc {{{sdc}}}")
        if period_lib is not None:
            # the clock_period knob wins over the SDC: redefine every clock on its own sources
            lines += [
                "foreach svkit_c [all_clocks] {",
                "  set svkit_src [get_property $svkit_c sources]",
                "  set svkit_n [get_name $svkit_c]",
                f"  if {{[llength $svkit_src]}} {{ create_clock -name $svkit_n -period {period_lib:.6g} $svkit_src }} "
                f"else {{ create_clock -name $svkit_n -period {period_lib:.6g} }}",
                "}",
            ]
    else:
        p = period_lib if period_lib is not None else None
        lines += [
            f"set svkit_clk_ports [get_ports -quiet {{{clock}}}]",
            "if {[llength $svkit_clk_ports]} {",
            f"  create_clock -name svkit_clk -period {p:.6g} $svkit_clk_ports",
            "} else {",
            f"  create_clock -name svkit_clk -period {p:.6g}",
            "}",
            "set svkit_inputs [all_inputs]",
            "if {[llength $svkit_clk_ports]} { set svkit_inputs [delete_from_list $svkit_inputs $svkit_clk_ports] }",
            "set_input_delay 0 -clock svkit_clk $svkit_inputs",
            "set_output_delay 0 -clock svkit_clk [all_outputs]",
        ]
    fields = "{cap slew input_pins nets}"
    lines += [
        f'puts "{MARK} units"', "report_units",
        f'puts "{MARK} clocks"', "foreach c [all_clocks] { puts \"clock [get_name $c] [get_property $c period]\" }",
        f'puts "{MARK} max"',
        f"report_checks -path_delay max -group_count {max_paths} -sort_by_slack -fields {fields} -digits 4",
        f'puts "{MARK} min"',
        f"report_checks -path_delay min -group_count {max_paths} -sort_by_slack -fields {fields} -digits 4",
        f'puts "{MARK} summary"',
        "report_worst_slack -max -digits 4",
        "report_tns -digits 4",
        f'puts "{MARK} summary_min"',
        "report_worst_slack -min -digits 4",
        f'puts "{MARK} power"', "report_power -digits 4",
        f'puts "{MARK} end"',
        "exit",
    ]
    return "\n".join(lines) + "\n"


# The SDC-less branch needs a period; replace None by the default before formatting.
def _period_or_default(period_lib: Optional[float], unit_ps: float) -> float:
    return period_lib if period_lib is not None else DEFAULT_PERIOD_PS / unit_ps


# ---------------------------------------------------------------------------- parsing
def split_sections(text: str) -> dict[str, str]:
    out: dict[str, list[str]] = {}
    cur = "_pre"
    for line in text.splitlines():
        if line.startswith(MARK + " "):
            cur = line[len(MARK) + 1:].strip()
            out.setdefault(cur, [])
            continue
        out.setdefault(cur, []).append(line)
    return {k: "\n".join(v) for k, v in out.items()}


def time_scale_ps(units_text: str) -> Optional[float]:
    """`report_units` output -> ps per library time unit (e.g. ' time 1ns' -> 1000)."""
    m = re.search(r"^\s*time\s+([\d.eE+-]*)\s*([munpf]?s)\b", units_text, re.MULTILINE)
    if not m:
        return None
    mult = float(m.group(1)) if m.group(1) else 1.0
    return mult * _TIME_UNITS.get(m.group(2), 1e3)


def _ps(v: float, scale: float) -> float:
    return round(v * scale, 4)


def _num(s: str) -> Optional[float]:
    try:
        v = float(s)
    except ValueError:
        return None
    return v if abs(v) < 1e30 else None


_ROW_PIN = re.compile(r"(?P<rf>[\^v])\s+(?P<name>\S+)\s+\((?P<cell>[^)]*)\)\s*$")
_ROW_NET = re.compile(r"^\s*(?P<name>\S+)\s+\(net\)\s*$")
_NUM = re.compile(r"^-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?$")


def parse_timing(text: str, scale: float = 1e3) -> list[TimingPath]:
    """Parse OpenSTA `report_checks` output (any number of paths). `scale` = ps per lib time unit."""
    paths: list[TimingPath] = []
    blocks = re.split(r"^(?=Startpoint:)", text, flags=re.MULTILINE)
    for b in blocks:
        if not b.startswith("Startpoint:"):
            continue
        p = _parse_path(b, scale)
        if p is not None:
            paths.append(p)
    return paths


def _parse_path(block: str, scale: float) -> Optional[TimingPath]:
    def hdr(key: str) -> Optional[str]:
        m = re.search(rf"^{key}:\s*(.+?)\s*$", block, re.MULTILINE)
        return m.group(1) if m else None

    start, end = hdr("Startpoint"), hdr("Endpoint")
    if start is None or end is None:
        return None
    strip = lambda s: re.sub(r"\s+\(.*\)\s*$", "", s)
    ptype = (hdr("Path Type") or "max").lower()
    slack = required = arrival = None
    points: list[TimingPoint] = []
    in_arrival = True
    seen_table = False
    for line in block.splitlines():
        s = line.strip()
        if s.startswith("---"):
            seen_table = True
            continue
        if not seen_table or not s:
            continue
        toks = s.split()
        nums = []
        for t in toks:
            if _NUM.match(t):
                nums.append(float(t))
            else:
                break
        desc = " ".join(toks[len(nums):])
        if "slack" in desc and nums:
            slack = _ps(nums[-1], scale)
            continue
        if desc.startswith("data arrival time"):
            if in_arrival and nums:
                arrival = _ps(nums[-1], scale)
            in_arrival = False
            continue
        if desc.startswith("data required time"):
            if required is None and nums:
                required = _ps(nums[-1], scale)
            continue
        if not in_arrival:
            continue
        mnet = _ROW_NET.match(s)
        if mnet and not nums:
            if points and points[-1].net is None:
                points[-1].net = mnet.group("name")
            continue
        m = _ROW_PIN.search(desc) if desc else None
        if m and len(nums) >= 2:
            name, cell = m.group("name"), m.group("cell").strip()
            if cell in ("in", "out", "inout"):
                inst, pin, lib_cell = "", name, None
            else:
                inst, _, pin = name.rpartition("/")
                lib_cell = cell or None
            points.append(TimingPoint(inst=inst, pin=pin, cell=lib_cell, incr=_ps(nums[-2], scale),
                                      arrival=_ps(nums[-1], scale),
                                      rise_fall="r" if m.group("rf") == "^" else "f"))
    if slack is None:
        return None
    return TimingPath(startpoint=strip(start), endpoint=strip(end), path_group=hdr("Path Group"),
                      path_type="min" if ptype.startswith("min") else "max", slack=slack,
                      required=required, arrival=arrival, points=points)


def _first_value(rx: str, text: str) -> Optional[float]:
    m = re.search(rx, text, re.MULTILINE)
    return _num(m.group(1)) if m else None


def parse_power(text: str) -> Power:
    """report_power table -> Power in mW (dynamic = internal + switching)."""
    unit = 1e3   # OpenSTA prints Watts
    mu = re.search(r"Power\s*\((\w+)\)", text)
    if mu:
        unit = _POWER_UNITS.get(mu.group(1).rstrip("s").replace("Watt", "W"), 1e3)
    m = re.search(r"^Total\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)", text, re.MULTILINE)
    if not m:
        return Power()
    internal, switching, leakage, total = (_num(x) for x in m.groups())
    dyn = (internal or 0.0) + (switching or 0.0) if internal is not None or switching is not None else None
    cv = lambda v: round(v * unit, 9) if v is not None else None
    return Power(dynamic=cv(dyn), leakage=cv(leakage), total=cv(total))


def parse_report(text: str, *, top: str = "", period_ps: Optional[float] = None) -> SynthResult:
    """Parse the full output of the generated STA script into a timing-only SynthResult."""
    sec = split_sections(text)
    scale = time_scale_ps(sec.get("units", "")) or 1e3
    res = SynthResult(tool="opensta", top=top, period=period_ps)
    if period_ps is None:
        m = re.search(r"^clock\s+\S+\s+([\d.eE+-]+)", sec.get("clocks", ""), re.MULTILINE)
        if m and _num(m.group(1)) is not None:
            res.period = _ps(_num(m.group(1)), scale)
    maxp = parse_timing(sec.get("max", ""), scale)
    minp = parse_timing(sec.get("min", ""), scale)
    maxp.sort(key=lambda p: p.slack)
    minp.sort(key=lambda p: p.slack)
    res.paths = maxp + minp
    ws = _first_value(r"^worst slack\s+(?:max\s+)?(\S+)", sec.get("summary", ""))
    res.wns = _ps(ws, scale) if ws is not None else (maxp[0].slack if maxp else None)
    tns = _first_value(r"^tns\s+(?:max\s+)?(\S+)", sec.get("summary", ""))
    res.tns = _ps(tns, scale) if tns is not None else None
    hs = _first_value(r"^worst slack\s+(?:min\s+)?(\S+)", sec.get("summary_min", ""))
    res.hold_wns = _ps(hs, scale) if hs is not None else (minp[0].slack if minp else None)
    if minp:
        res.hold_tns = sum(min(0.0, p.slack) for p in minp)
    res.power = parse_power(sec.get("power", ""))
    for line in text.splitlines():
        m = re.match(r"^(Warning|Error):\s*(.*)$", line.strip())
        if m and len(res.warnings) < 100:
            res.warnings.append(Msg(severity=Severity.error if m.group(1) == "Error" else Severity.warning,
                                    text=m.group(2), code="sta"))
    res.extra["sta_time_unit_ps"] = scale
    return res


# ---------------------------------------------------------------------------- adapter
class OpenStaAdapter(StaAdapter):
    name = "opensta"
    tools = ("sta",)

    def parse_timing(self, text: str) -> list[TimingPath]:
        scale = time_scale_ps(text) or 1e3
        return parse_timing(text, scale)

    def run(self, ctx: RunContext, flow: StaFlow, *, netlist: Path, top: str, liberty: list[Path],
            period_ps: float | None) -> SynthResult:
        cfg = ctx.cfg
        exe = cfg.tool("sta")
        unit_ps = liberty_time_unit_ps(liberty) or 1e3
        sdc = None
        if flow.sdc:
            sdc = Path(P.tmpl(flow.sdc, cfg, workdir=ctx.workdir, run_dir=ctx.run_dir))
            if not sdc.is_absolute():
                sdc = ctx.workdir / sdc
        period_lib = period_ps / unit_ps if period_ps is not None else None
        if sdc is None:
            if period_lib is None:
                ctx.log(f"[svkit] no clock_period knob and no SDC: using {DEFAULT_PERIOD_PS:g} ps")
                period_ps = DEFAULT_PERIOD_PS
            period_lib = _period_or_default(period_lib, unit_ps)
        netlist = sta_netlist(netlist, ctx.workdir)
        tcl = build_tcl(liberty=liberty, netlist=netlist, top=top, clock=cfg.project.clock,
                        period_lib=period_lib, sdc=sdc, max_paths=max(1, flow.max_paths))
        script = ctx.workdir / "svkit_sta.tcl"
        script.write_text(tcl)
        out = ctx.workdir / "sta.log"
        if out.exists():
            out.unlink()
        rc = ctx.sh([exe, "-no_init", "-exit", str(script)], cwd=ctx.workdir, log_file=out,
                    extra_env=flow.env)
        text = out.read_text(errors="replace") if out.exists() else ""
        ctx.keep(script, "sta.tcl")
        if out.exists():
            ctx.keep(out, "sta.log")
        if rc != 0 or f"{MARK} end" not in text:
            raise RuntimeError(f"OpenSTA failed (exit {rc}); see artifact sta.log")
        return parse_report(text, top=top, period_ps=period_ps)


def liberty_time_unit_ps(liberty: list[Path]) -> Optional[float]:
    """Read `time_unit : "1ns";` from the first liberty file that declares it."""
    for lib in liberty:
        try:
            with open(lib, errors="replace") as fh:
                head = fh.read(200_000)
        except OSError:
            continue
        m = re.search(r"time_unit\s*:\s*\"?\s*([\d.]+)\s*([munpf]?s)\s*\"?", head)
        if m:
            return float(m.group(1)) * _TIME_UNITS.get(m.group(2), 1e3)
    return None
