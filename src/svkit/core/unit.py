"""Unit-test suites: one testbench file per test (`[flows.sim.<x>].testbench`).

A unit test compiles the design sources (`[project].sources`), the flow's extra `sources` and
its own testbench file, with the module declared in that file as the simulation top. Unless the
testbench dumps a waveform itself, svkit adds a generated module, bound into the top, that dumps
every signal to the file named by the `+svkit_waves=<path>` plusarg. Nothing the user wrote is
edited: the generated file lives in svkit's build cache.
"""
from __future__ import annotations

import fnmatch
import re
from pathlib import Path
from typing import Optional

from svkit.config import Config, ConfigError, SimFlow
from svkit.core import project as P
from svkit.schemas import Divergence

WAVES_PLUSARG = "svkit_waves"
_COMMENTS = re.compile(r"//[^\n]*|/\*.*?\*/", re.S)
_MODULE = re.compile(r"^\s*(?:macro)?module\s+(?:automatic\s+|static\s+)?(\w+)", re.M)
_OWN_DUMP = re.compile(r"\$(?:dumpfile|dumpvars|vcdplus\w*|fsdbDump\w*)\b")
# a check failing in the log (used to find the first error when no golden output is compared)
DEFAULT_ERROR_RE = r"(?i)\b(?:error|fail(?:ed|ure)?|mismatch|assert(?:ion)?\s+failed)\b"
_TIME_RES = [re.compile(p) for p in (r"\[\s*(\d+)\s*(?:[fpnum]?s)?\s*\]", r"@\s*(\d+)", r"(?i)\btime\s*[=:]?\s*(\d+)",
                                     r"^\s*(\d+)\s*[:|]")]


def _split(template: str) -> tuple[str, str]:
    a, _, b = template.partition("{test}")
    return a, b


def testbench_file(cfg: Config, fl: SimFlow, test: str) -> Path:
    assert fl.testbench
    return (cfg.root / P.tmpl(fl.testbench, cfg, test=test)).resolve()


def discover(cfg: Config, fl: SimFlow) -> list[str]:
    """Test names of a flow: `tests.names`, `tests.glob` stems and (unit suites) the {test} part of
    every file matching `testbench`, minus `tests.exclude` and the system testbench's own files."""
    names = list(fl.tests.names)
    if fl.tests.glob:
        names += [p.stem for p in sorted(cfg.root.glob(fl.tests.glob))]
    if fl.testbench:
        a, b = _split(fl.testbench)
        rx = re.compile(re.escape(a) + r"(.+?)" + re.escape(b) + r"$")
        system = {f for f in P.resolve_sources(cfg, cfg.project.tb_sources)}
        for p in sorted(cfg.root.glob(a + "*" + b)):
            m = rx.match(p.relative_to(cfg.root).as_posix())
            if m and p.resolve() not in system:
                names.append(m.group(1))
    names = [n for n in names if not any(fnmatch.fnmatchcase(n, x) for x in fl.tests.exclude)]
    return list(dict.fromkeys(names))


def declared_modules(text: str) -> list[str]:
    return _MODULE.findall(_COMMENTS.sub("", text))


def testbench_top(cfg: Config, fl: SimFlow, test: str) -> str:
    """`top` if set, else the module declared in the testbench file that nothing else in it
    instantiates (the first one if that is ambiguous)."""
    if fl.top:
        return P.tmpl(fl.top, cfg, test=test)
    f = testbench_file(cfg, fl, test)
    try:
        text = _COMMENTS.sub("", f.read_text(errors="replace"))
    except OSError as e:
        raise ConfigError(f"unit test {test!r}: cannot read testbench {f}: {e}") from e
    mods = declared_modules(text)
    if not mods:
        raise ConfigError(f"unit test {test!r}: {f.name} declares no module (set `top` in the flow)")
    roots = [m for m in mods if not re.search(rf"^\s*{m}\s+(?:#\s*\(.*?\)\s*)?\w+\s*\(", text, re.M | re.S)]
    return (roots or mods)[0]


def dumps_itself(path: Path) -> bool:
    try:
        return bool(_OWN_DUMP.search(_COMMENTS.sub("", path.read_text(errors="replace"))))
    except OSError:
        return False


def waves_module(build_root: Path, top: str) -> Path:
    """Generated source that dumps the whole design under `top` (bound into it)."""
    build_root.mkdir(parents=True, exist_ok=True)
    f = build_root / f"svkit_waves_{top}.sv"
    text = (f"// generated by svkit: waveform dump for unit testbench {top} (not part of your project)\n"
            "module svkit_waves;\n"
            "  string svkit_f;\n"
            "  initial begin\n"
            f'    if (!$value$plusargs("{WAVES_PLUSARG}=%s", svkit_f)) svkit_f = "waves.vcd";\n'
            "    $dumpfile(svkit_f);\n"
            "    $dumpvars;\n"
            "  end\n"
            "endmodule\n"
            f"bind {top} svkit_waves svkit_waves_i();\n")
    if not f.is_file() or f.read_text() != text:
        f.write_text(text)
    return f


class UnitBuild:
    """What a builtin adapter compiles for one unit test."""

    def __init__(self, cfg: Config, fl: SimFlow, test: str, build_root: Path):
        self.testbench = testbench_file(cfg, fl, test)
        if not self.testbench.is_file():
            raise ConfigError(f"unit test {test!r}: no testbench file {self.testbench}")
        self.top = testbench_top(cfg, fl, test)
        files = P.resolve_sources(cfg) + P.resolve_sources(cfg, fl.sources) + [self.testbench]
        self.waves: Optional[Path] = None            # generated dump module, if one is needed
        if not dumps_itself(self.testbench):
            self.waves = waves_module(build_root, self.top)
            files.append(self.waves)
        self.files = list(dict.fromkeys(files))

    def run_args(self, run_dir: Path) -> list[str]:
        return [f"+{WAVES_PLUSARG}={run_dir / 'waves.vcd'}"] if self.waves else []


def sim_sources(cfg: Config, fl: SimFlow) -> list[Path]:
    """Files besides [project].sources whose content affects a run of this flow (cache key)."""
    return P.resolve_sources(cfg, fl.sources)


def log_divergence(log_text: str, error_regex: Optional[str]) -> Optional[Divergence]:
    """First log line reporting a failed check, with the sim time printed on it (if any)."""
    rx = re.compile(error_regex or DEFAULT_ERROR_RE)
    for i, line in enumerate(log_text.splitlines(), 1):
        m = rx.search(line)
        if not m:
            continue
        t = m.groupdict().get("time")
        if t is None:
            for tr in _TIME_RES:
                if mt := tr.search(line):
                    t = mt.group(1)
                    break
        return Divergence(line=i, actual=line.strip()[:500], time=int(t) if t and t.isdigit() else None,
                          source="log")
    return None
